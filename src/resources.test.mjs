import assert from 'node:assert/strict';
import {loadTs} from './test-module.mjs';
const {steelHeart}=await loadTs('./rule-types.ts');
const {defaultMechanics}=await loadTs('./mechanics.ts');
const {actionPatch,validateResourceState,resourceValue,actionStatus}=await loadTs('./resource-engine.ts');
const {validateRuleStateChange}=await loadTs('./rule-engine.ts');
const {validateModule}=await loadTs('./rule-schema.ts');
const config=defaultMechanics();config.modules={steel_heart:steelHeart};
const zero={strength:0,dexterity:0,constitution:0,intelligence:0,wisdom:0,charisma:0};
const c={hp:20,race:'人类',class_levels:[],strength:10,dexterity:10,constitution:10,intelligence:10,wisdom:10,charisma:10,ability_permanent:zero,ability_temporary:zero,editable_fields:[],rule_state:{instances:[{id:'s1',moduleId:'steel_heart',enabled:false,access:'gm',params:{}}],weapon:{}}};
assert.equal(resourceValue(c.rule_state,'s1','damage_buffer',steelHeart.resources.damage_buffer),0);
assert.match(actionStatus(c,config,'s1','settle_damage',false),/不满足/);
const state=structuredClone(c.rule_state);state.resourceValues={s1:{damage_buffer:25}};
validateRuleStateChange(c,config,state,false);validateResourceState(c,config,state,false);
const original=JSON.stringify(state),patch=actionPatch({...c,rule_state:state},config,'s1','settle_damage',false);
assert.equal(patch.hp,-5);assert.equal(patch.rule_state.resourceValues.s1.damage_buffer,0);assert.equal(JSON.stringify(state),original);
assert.throws(()=>actionPatch({...c,...patch},config,'s1','settle_damage',false),/不满足/);
assert.throws(()=>validateResourceState(c,config,{...state,resourceValues:{s1:{damage_buffer:-1}}},false),/范围/);
assert.throws(()=>validateResourceState(c,config,{...state,resourceValues:{s1:{damage_buffer:1.5}}},false),/整数/);
const locked=structuredClone(config);locked.modules.steel_heart.resources.damage_buffer.playerEditable=false;
assert.throws(()=>validateResourceState(c,locked,state,false),/未开放/);
const noAction=structuredClone(config);noAction.modules.steel_heart.actions[0].playerUsable=false;
assert.throws(()=>actionPatch({...c,rule_state:state},noAction,'s1','settle_damage',false),/仅限/);
const bad=structuredClone(steelHeart);bad.actions[0].changes[0].target='other.hp';assert.throws(()=>validateModule(bad,{}),/只能修改/);
const twice={...state,instances:[...state.instances,{...state.instances[0],id:'s2'}],resourceValues:{s1:{damage_buffer:3},s2:{damage_buffer:8}}};
const p2=actionPatch({...c,rule_state:twice},config,'s1','settle_damage',false);assert.equal(p2.hp,17);assert.equal(p2.rule_state.resourceValues.s2.damage_buffer,8);
assert.deepEqual(JSON.parse(JSON.stringify(p2)).rule_state,p2.rule_state);
const off={...c.rule_state,instances:[{...c.rule_state.instances[0],enabled:true}]};assert.throws(()=>validateRuleStateChange(c,config,off,false),/GM 控制/);
console.log('Resources: passive zero state, atomic damage settlement, negative HP, replay prevention, permissions, bounds, instance isolation and JSON persistence passed');

const invalidFinal=structuredClone(config);invalidFinal.modules.steel_heart.actions[0].changes[1].value='-1';
const beforeFailure=JSON.stringify({...c,rule_state:state});
assert.throws(()=>actionPatch({...c,rule_state:state},invalidFinal,'s1','settle_damage',false),/范围/);
assert.equal(JSON.stringify({...c,rule_state:state}),beforeFailure);
console.log('Invalid second assignment rolls back the complete action');
